//Logics of const

const name = 'Bangladesh';

// const name = 'Pakistan' -> Cannot reassign the variable
// name = 'Afganistan' -> Cannot update the value of variable

const newName = 'Dhaka_'+name; //This is valid to use the variable in different ways

//Logics of let

let price = 120;
price = 150; // In let, we can reuse, redeclare, reassign a variable

console.log(price);

